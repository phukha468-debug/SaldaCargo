import type {
  ClientOrderPart,
  OrderItem,
  RawRouteStop,
  RouteStop,
  SmartOrderFormState,
} from '../types';

export function isAutoGeneratedOrder(order?: OrderItem | null): boolean {
  return Boolean(
    order?.base_doc_name?.includes('ВЫЕЗД БЕЗ ЗАЯВКИ') ||
    order?.base_doc_number?.startsWith('АВТО-') ||
    order?.cargo_name?.includes('Выезд без заявки') ||
    order?.cargo_name?.includes('⚠️'),
  );
}

export function initRoutesFromOrder(initialOrder?: OrderItem | null): RouteStop[] {
  const existing = initialOrder?.routes_json || initialOrder?.raw_parser_payload?.routes;
  if (existing && Array.isArray(existing) && existing.length > 0) {
    return (existing as RawRouteStop[]).map((r, idx) => ({
      id: String(idx + 1),
      loading_city: r.loading_city || r.loadingCity || '',
      loading_address: r.loading_address || r.loadingAddress || '',
      loading_org: r.loading_org || r.clientName || '',
      unloading_city: r.unloading_city || r.unloadingCity || '',
      unloading_address: r.unloading_address || r.unloadingAddress || '',
      unloading_org: r.unloading_org || '',
      cargo_name: r.cargo_name || r.cargoName || '',
      weight_kg: r.weight_kg
        ? Number(r.weight_kg)
        : r.weightTons
          ? Math.round(Number(r.weightTons) * 1000)
          : 0,
    }));
  }

  const isAutoOrder = isAutoGeneratedOrder(initialOrder);
  const rawLoad =
    initialOrder?.loading_address_json?.raw || initialOrder?.loading_address_json?.address || '';
  const cleanLoad =
    (isAutoOrder && rawLoad === 'База Салда') || rawLoad.includes('⚠️') ? '' : rawLoad;

  const rawUnload =
    initialOrder?.unloading_address_json?.raw ||
    initialOrder?.unloading_address_json?.address ||
    '';
  const cleanUnload = rawUnload.includes('⚠️') ? '' : rawUnload;

  const rawCargo = initialOrder?.cargo_name || '';
  const cleanCargo =
    rawCargo.includes('⚠️') || rawCargo.includes('Выезд без заявки') ? '' : rawCargo;

  return [
    {
      id: '1',
      loading_city: cleanLoad
        ? initialOrder?.loading_address_json?.city || cleanLoad.split(',')[0] || ''
        : '',
      loading_address: cleanLoad,
      loading_org: initialOrder?.loading_org_name || '',
      unloading_city: cleanUnload
        ? initialOrder?.unloading_address_json?.city || cleanUnload.split(',')[0] || ''
        : '',
      unloading_address: cleanUnload,
      unloading_org: initialOrder?.client?.name || '',
      cargo_name: cleanCargo,
      weight_kg: initialOrder?.weight_gross_kg && !isAutoOrder ? initialOrder.weight_gross_kg : 0,
    },
  ];
}

export function initClientOrdersFromOrder(initialOrder?: OrderItem | null): ClientOrderPart[] {
  const existing = initialOrder?.client_orders || initialOrder?.raw_parser_payload?.client_orders;
  if (Array.isArray(existing) && existing.length > 0) {
    return existing.map((co, idx) => ({
      id: co.id || String(idx + 1),
      client_id: co.client_id || '',
      client_name: co.client_name || '',
      client_inn: co.client_inn || '',
      base_doc_number: co.base_doc_number || '',
      cargo_name: co.cargo_name || '',
      weight_gross_kg: co.weight_gross_kg !== undefined ? co.weight_gross_kg : '',
      price_without_vat: co.price_without_vat !== undefined ? co.price_without_vat : '',
      forwarder_id: co.forwarder_id || '',
      forwarder_name: co.forwarder_name || '— (Прямой заказчик)',
      payment_method: co.payment_method || 'bank_invoice',
      payment_terms: co.payment_terms || 'Безналичный расчет (Дебиторская задолженность)',
    }));
  }

  if (initialOrder) {
    const isAutoOrder = isAutoGeneratedOrder(initialOrder);
    const rawDoc =
      initialOrder.base_doc_number ||
      (initialOrder.trip?.trip_number
        ? String(initialOrder.trip.trip_number)
        : String(initialOrder.order_number));
    const cleanDoc = rawDoc.startsWith('АВТО-')
      ? initialOrder.trip?.trip_number
        ? String(initialOrder.trip.trip_number)
        : ''
      : rawDoc;
    const rawCargo = initialOrder.cargo_name || '';
    const cleanCargo =
      rawCargo.includes('⚠️') || rawCargo.includes('Выезд без заявки') ? '' : rawCargo;

    return [
      {
        id: '1',
        client_id: initialOrder.client?.id || '',
        client_name: initialOrder.client?.name || '',
        client_inn: initialOrder.client?.inn || '',
        base_doc_number: cleanDoc,
        cargo_name: cleanCargo,
        weight_gross_kg:
          initialOrder.weight_gross_kg && !isAutoOrder ? initialOrder.weight_gross_kg : '',
        price_without_vat:
          initialOrder.price_without_vat && !isAutoOrder ? initialOrder.price_without_vat : '',
        forwarder_id: initialOrder.forwarder?.id || '',
        forwarder_name: initialOrder.forwarder?.name || '— (Прямой заказчик)',
        payment_method: initialOrder.payment_terms?.includes('Наличные') ? 'cash' : 'bank_invoice',
        payment_terms:
          initialOrder.payment_terms || 'Безналичный расчет (Дебиторская задолженность)',
      },
    ];
  }

  return [
    {
      id: '1',
      client_id: '',
      client_name: '',
      client_inn: '',
      base_doc_number: '',
      cargo_name: '',
      weight_gross_kg: '',
      price_without_vat: '',
      forwarder_id: '',
      forwarder_name: '— (Прямой заказчик)',
      payment_method: 'bank_invoice',
      payment_terms: 'Безналичный расчет (Дебиторская задолженность)',
    },
  ];
}

export function initSmartOrderForm(initialOrder?: OrderItem | null): SmartOrderFormState {
  const today = new Date().toISOString().slice(0, 10);
  if (initialOrder) {
    return {
      base_doc_number: initialOrder.base_doc_number || String(initialOrder.order_number),
      base_doc_date: initialOrder.base_doc_date || initialOrder.created_at?.slice(0, 10) || today,
      client_id: initialOrder.client?.id || '',
      client_name: initialOrder.client?.name || '',
      client_inn: initialOrder.client?.inn || '',
      forwarder_id: initialOrder.forwarder?.id || '',
      forwarder_name: initialOrder.forwarder?.name || '— (Прямой заказчик)',
      preset_id: '',
      loading_point_id: '',
      loading_address: initialOrder.loading_address_json?.raw || '',
      loading_city: initialOrder.loading_address_json?.city || '',
      loading_org_name: initialOrder.loading_org_name || '',
      unloading_address: initialOrder.unloading_address_json?.raw || '',
      unloading_city: initialOrder.unloading_address_json?.city || '',
      cargo_name: initialOrder.cargo_name || '',
      weight_gross_kg:
        initialOrder.weight_gross_kg !== undefined ? initialOrder.weight_gross_kg : '',
      places_count: initialOrder.places_count || 1,
      packaging_type: initialOrder.packaging_type || 'паллеты',
      price_without_vat:
        initialOrder.price_without_vat !== undefined ? initialOrder.price_without_vat : '',
      payment_method: initialOrder.payment_terms?.includes('Наличные') ? 'cash' : 'bank_invoice',
      payment_terms:
        initialOrder.payment_terms ||
        'Безналичный расчет (Дебиторская задолженность, отсрочка 15 дней)',
      planned_loading_at: initialOrder.planned_loading_at?.slice(0, 16) || `${today}T08:00`,
      planned_delivery_at: initialOrder.planned_delivery_at?.slice(0, 16) || `${today}T18:00`,
      assigned_vehicle_id: initialOrder.assigned_vehicle_id || '',
      assigned_driver_id: initialOrder.assigned_driver_id || '',
    };
  }

  return {
    base_doc_number: '',
    base_doc_date: today,
    client_id: '',
    client_name: '',
    client_inn: '',
    forwarder_id: '',
    forwarder_name: '— (Прямой заказчик)',
    preset_id: '',
    loading_point_id: '',
    loading_address: '',
    loading_city: '',
    loading_org_name: '',
    unloading_address: '',
    unloading_city: '',
    cargo_name: '',
    weight_gross_kg: '',
    places_count: 1,
    packaging_type: 'паллеты',
    price_without_vat: '',
    payment_method: 'bank_invoice',
    payment_terms: 'Безналичный расчет (Дебиторская задолженность)',
    planned_loading_at: `${today}T08:00`,
    planned_delivery_at: `${today}T18:00`,
    assigned_vehicle_id: '',
    assigned_driver_id: '',
  };
}
